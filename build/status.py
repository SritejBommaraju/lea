#!/usr/bin/env python3
"""build/status.py: write build/STATUS.md (what is done, what is left, what is blocked, milestones).

Run:  python3 -I build/status.py [--stdout] [--offline]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _lib  # noqa: E402
import next as next_tool  # noqa: E402

OUT = _lib.ROOT / "build" / "STATUS.md"


def render(data, results) -> str:
    by_id = data["by_id"]
    plan = next_tool.plan(data, results=results)
    ready = {r["id"] for g in plan.values() for r in g["ready"]}
    waiting = {r["id"]: r for g in plan.values() for r in g["waiting"]}
    lines = ["# LEA build status", "",
             "Generated by `python3 -I build/status.py` from `build/tasks.yaml` and the commits on main. "
             "Do not edit by hand.", "",
             "| Stream | Done | In progress | Ready | Not ready yet | Total |", "|---|---|---|---|---|---|"]
    for s in data["streams"]:
        ts = [t for t in data["tasks"] if t["stream"] == s["id"] and t["status"] != "removed"]
        n = {k: sum(t["status"] == k for t in ts) for k in ("done", "doing")}
        lines.append(f"| {s['name']} | {n['done']} | {n['doing']} | {sum(t['id'] in ready for t in ts)} | "
                     f"{len(ts) - n['done'] - n['doing'] - sum(t['id'] in ready for t in ts)} | {len(ts)} |")
    lines += ["", "## Milestones", "", "| Id | Milestone | Tasks done |", "|---|---|---|"]
    for m in data["milestones"]:
        done, total = _lib.milestone_progress(data, m)
        lines.append(f"| {m['id']} | {m['title']} | {done}/{total}{' (met)' if done == total else ''} |")
    for s in data["streams"]:
        lines += ["", f"## {s['name']}", "", "| Task | State | Title |", "|---|---|---|"]
        for t in (t for t in data["tasks"] if t["stream"] == s["id"] and t["status"] != "removed"):
            if t["status"] == "done":
                state = "done"
            elif t["status"] == "doing":
                state = f"in progress (`{t['branch']}`)"
            elif t["id"] in ready:
                state = "ready"
            elif t["id"] in waiting:
                r = waiting[t["id"]]
                state = "blocked" if r["status"] == "blocked" else "needs human: " + ", ".join(r["missing"])
            else:
                state = "after " + ", ".join(d for d in t["depends_on"] if by_id[d]["status"] != "done")
            lines.append(f"| {t['id']} | {state} | {t['title']} |")
    removed = [t for t in data["tasks"] if t["status"] == "removed"]
    if removed:
        lines += ["", "## Removed", "", "| Task | Title |", "|---|---|"]
        lines += [f"| {t['id']} | {t['title']} |" for t in removed]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stdout", action="store_true", help="print instead of writing build/STATUS.md")
    ap.add_argument("--offline", action="store_true")
    args = ap.parse_args()
    data = _lib.load_tasks()
    errs = _lib.validate_tasks(data)
    if errs:
        print("build/tasks.yaml has errors; fix them first:", *errs, sep="\n  - ", file=sys.stderr)
        return 2
    steps = {h for t in _lib.open_tasks(data) for h in t["human"]}
    text = render(data, _lib.check_steps(data, steps, offline=args.offline))
    if args.stdout:
        print(text, end="")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(_lib.ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
