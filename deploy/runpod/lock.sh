#!/usr/bin/env bash
# Re-pin the Linux x86_64 (Runpod) dependency set: deploy/runpod/requirements.linux.lock.
#
#   deploy/runpod/lock.sh            # run from anywhere; needs uv
#
# Why a second lock: backend/requirements.lock is compiled on the Mac, so it has no torch CUDA dependencies
# (nvidia-*, triton). This one is compiled for manylinux x86_64 with torch from the PyTorch cu126 index (CUDA 12.6:
# Ampere/Ada/Hopper GPUs, any Runpod host driver >= 525), and every package that is also in
# backend/requirements.lock is held to that exact version (constraints), so the cloud runs what the Mac runs.
# Extras: vision (torch, transformers, the detector) and geometry (open3d, the app's 3D scan mesh,
# repairos/pipeline/mesh.py; open3d 0.20 ships manylinux_2_35 wheels only, hence that tag; the image's Debian bookworm
# has glibc 2.36). Dev extras (pytest) are left out of the image. Every line carries hashes; the Dockerfile installs with
# --require-hashes.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# Same versions as the Mac lock, minus torch (the CUDA build is pinned below) and the dev-only test tools.
grep -E '^[A-Za-z0-9]' "$root/backend/requirements.lock" | grep -vE '^(torch|pytest|iniconfig|pluggy)==' > "$tmp/constraints.txt"
torch_pin="$(grep -E '^torch==' "$root/backend/requirements.lock" | cut -d= -f3)"
echo "torch==${torch_pin}+${TORCH_CUDA:-cu126}" > "$tmp/torch.in"

cd "$root"
uv pip compile --python 3.12 --python-platform x86_64-manylinux_2_35 \
  backend/pyproject.toml "$tmp/torch.in" --extra vision --extra geometry -c "$tmp/constraints.txt" \
  --index "https://download.pytorch.org/whl/${TORCH_CUDA:-cu126}" --index-strategy unsafe-best-match \
  --generate-hashes --no-annotate --no-header -o "$here/requirements.linux.lock"
sed -i.bak '1i\
# Generated by deploy/runpod/lock.sh (uv pip compile, x86_64-manylinux_2_35, extras vision + geometry, torch\
# from the PyTorch cu126 index, versions held to backend/requirements.lock). Do not edit; re-run the script.
' "$here/requirements.linux.lock" && rm -f "$here/requirements.linux.lock.bak"
echo "wrote $here/requirements.linux.lock ($(grep -cE '^[a-z]' "$here/requirements.linux.lock") packages)"
