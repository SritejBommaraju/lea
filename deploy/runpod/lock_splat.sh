#!/usr/bin/env bash
# Re-pin the splat add-on: deploy/runpod/requirements.splat.lock, the packages gsplat (nerfstudio-project/gsplat,
# Apache-2.0) adds on top of requirements.linux.lock, hash-pinned. bootstrap.sh installs it with LEA_SPLAT=1, in the
# background, into the volume venv (--no-deps --require-hashes), so the main lock and its venv marker stay as they are.
#
#   deploy/runpod/lock_splat.sh      # needs uv
#
# Why gsplat's py3-none-any wheel and not a prebuilt CUDA wheel: the prebuilt index (https://docs.gsplat.studio/whl/
# gsplat/, read 2026-10-24) stops at torch 2.4 + cu124 and cp310; there is none for torch 2.14.1+cu126 on Python 3.12.
# The plain wheel compiles its CUDA kernels on first use (torch.utils.cpp_extension JIT, gsplat/cuda/_backend.py) with
# the image's nvcc; bootstrap.sh does that once into $TORCH_EXTENSIONS_DIR on the volume.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
GSPLAT="${GSPLAT:-gsplat==1.5.3}"
grep -E '^[A-Za-z0-9]' "$here/requirements.linux.lock" | sed 's/ \\$//' > "$tmp/constraints.txt"
echo "$GSPLAT" > "$tmp/splat.in"
uv pip compile --python 3.12 --python-platform x86_64-manylinux_2_35 "$tmp/splat.in" -c "$tmp/constraints.txt" \
  --index "https://download.pytorch.org/whl/${TORCH_CUDA:-cu126}" --index-strategy unsafe-best-match \
  --no-annotate --no-header -o "$tmp/full.txt" >/dev/null
# only what the main lock does not already have
grep -E '^[a-z0-9]' "$tmp/full.txt" | sort -u > "$tmp/a"
tr 'A-Z' 'a-z' < "$tmp/constraints.txt" | sort -u > "$tmp/b"
comm -23 "$tmp/a" "$tmp/b" > "$tmp/new.in"
uv pip compile --python 3.12 --python-platform x86_64-manylinux_2_35 "$tmp/new.in" --no-deps \
  --generate-hashes --no-annotate --no-header -o "$tmp/new.lock" >/dev/null
{ echo "# Generated by deploy/runpod/lock_splat.sh: what $GSPLAT adds to requirements.linux.lock (x86_64-manylinux_2_35,"
  echo "# Python 3.12). Do not edit; re-run the script. Installed by bootstrap.sh with LEA_SPLAT=1 (--no-deps)."
  cat "$tmp/new.lock"; } > "$here/requirements.splat.lock"
echo "wrote $here/requirements.splat.lock ($(grep -cE '^[a-z]' "$here/requirements.splat.lock") packages)"
