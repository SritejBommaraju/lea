#!/usr/bin/env python3
"""Generate typed contract models from spec/contracts/*.schema.json (PLAN.md task B2).

    python3 -I tools/codegen/codegen.py           # write the generated files
    python3 -I tools/codegen/codegen.py --check   # regenerate into a temp dir, fail on any difference (drift)

Outputs (never hand-edit them):
    backend/repairos/contracts/*.py      Pydantic v2, one module per schema; __init__.py maps schema name -> model
    ios/RepairOS/Contracts/Contracts.swift   Swift Codable + Sendable structs for every schema

Tools, pinned here and run in their own throwaway environments (they are not project dependencies):
    datamodel-code-generator (MIT) via `uvx`, formatted with black (MIT) + isort (MIT)
    quicktype (Apache-2.0) via `npx`
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONTRACTS = ROOT / "spec" / "contracts"
PY_OUT = ROOT / "backend" / "repairos" / "contracts"
SWIFT_OUT = ROOT / "ios" / "RepairOS" / "Contracts"

DATAMODEL_CODEGEN = ["uvx", "--python", "3.12", "--from", "datamodel-code-generator==0.86.0",
                     "--with", "black==26.10.1", "--with", "isort==8.0.1", "datamodel-codegen"]
QUICKTYPE = ["npx", "--yes", "quicktype@26.0.0"]
HEADER = "GENERATED by tools/codegen/codegen.py from spec/contracts/{src}. Do not edit; run `make codegen`."


def schemas() -> list[Path]:
    return sorted(CONTRACTS.glob("*.schema.json"))


def schema_name(path: Path) -> str:
    return path.name[: -len(".schema.json")]


def module_name(path: Path) -> str:
    return schema_name(path).replace("-", "_") + "_schema"


def run(cmd: list[str], cwd: Path) -> None:
    res = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if res.returncode != 0:
        sys.exit(f"codegen: {' '.join(cmd[:4])} ... failed ({res.returncode}):\n{res.stdout}\n{res.stderr}")


def gen_python(out: Path) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "schemas"
        src.mkdir()
        for p in schemas():
            shutil.copy(p, src / p.name)
        gen = Path(tmp) / "out"
        run(DATAMODEL_CODEGEN + [
            "--input", str(src), "--input-file-type", "jsonschema", "--output", str(gen),
            "--output-model-type", "pydantic_v2.BaseModel", "--target-python-version", "3.12",
            "--use-standard-collections", "--use-union-operator", "--field-constraints", "--strict-nullable",
            "--use-schema-description", "--disable-timestamp", "--formatters", "black", "isort",
        ], cwd=Path(tmp))
        out.mkdir(parents=True, exist_ok=True)
        for p in schemas():
            body = (gen / f"{module_name(p)}.py").read_text(encoding="utf-8")
            (out / f"{module_name(p)}.py").write_text(f"# {HEADER.format(src=p.name)}\n{body}", encoding="utf-8")
        lines = [f'"""{HEADER.format(src="*.schema.json")}', "",
                 "MODELS maps a schema name (file name without .schema.json) to its top-level model.", '"""', ""]
        lines += [f"from . import {module_name(p)}" for p in schemas()]
        lines += ["", "MODELS = {"]
        for p in schemas():
            title = json.loads(p.read_text(encoding="utf-8"))["title"]
            lines.append(f'    "{schema_name(p)}": {module_name(p)}.{title},')
        lines += ["}", "", VALIDATE_PY]
        (out / "__init__.py").write_text("\n".join(lines), encoding="utf-8")


# Appended to the generated contracts/__init__.py. The models cannot express the schemas' `if/then` rules (for
# example "continuity needs pins", "a power-on step needs safety_gate"), so validate() checks the full JSON Schema
# first, then builds the typed model.
VALIDATE_PY = '''
import json as _json
from functools import cache as _cache
from pathlib import Path as _Path
from typing import Any as _Any

import jsonschema as _jsonschema
from pydantic import BaseModel as _BaseModel
from referencing import Registry as _Registry, Resource as _Resource

SCHEMA_DIR = _Path(__file__).resolve().parents[3] / "spec" / "contracts"


@_cache
def _validators() -> dict[str, _jsonschema.Draft202012Validator]:
    docs = {p.name: _json.loads(p.read_text(encoding="utf-8")) for p in SCHEMA_DIR.glob("*.schema.json")}
    registry = _Registry().with_resources((n, _Resource.from_contents(d)) for n, d in docs.items())
    return {n[: -len(".schema.json")]: _jsonschema.Draft202012Validator(d, registry=registry) for n, d in docs.items()}


def validate(name: str, data: _Any) -> _BaseModel:
    """Validate `data` against spec/contracts/<name>.schema.json (all rules), then return the typed model.
    Raises jsonschema.ValidationError or pydantic.ValidationError."""
    _validators()[name].validate(data)
    return MODELS[name].model_validate(data)
'''


def gen_swift(out: Path) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        target = Path(tmp) / "Contracts.swift"
        run(QUICKTYPE + [
            "--src-lang", "schema", "--lang", "swift", "--struct-or-class", "struct", "--coding-keys",
            "--sendable", "--no-initializers", "--access-level", "public", "-o", str(target),
            *[str(p) for p in schemas()],
        ], cwd=CONTRACTS)
        text = target.read_text(encoding="utf-8")
        # JSONAny/JSONNull hold immutable decoded values; Swift 6 strict concurrency needs them Sendable too.
        text = text.replace("public class JSONNull: Codable, Hashable {",
                            "public final class JSONNull: Codable, Hashable, Sendable {")
        text = text.replace("public class JSONAny: Codable {", "public final class JSONAny: Codable, @unchecked Sendable {")
        text = text.replace("\nclass JSONCodingKey: CodingKey {", "\nfinal class JSONCodingKey: CodingKey {")
        out.mkdir(parents=True, exist_ok=True)
        (out / "Contracts.swift").write_text(f"// {HEADER.format(src='*.schema.json')}\n{text}", encoding="utf-8")


def generate(py_out: Path, swift_out: Path) -> None:
    for d in (py_out, swift_out):
        if d.exists():
            shutil.rmtree(d)
    gen_python(py_out)
    gen_swift(swift_out)


def tree(d: Path) -> dict[str, bytes]:
    return {str(p.relative_to(d)): p.read_bytes() for p in sorted(d.rglob("*"))
            if p.is_file() and "__pycache__" not in p.parts}


def check() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        py_tmp, swift_tmp = Path(tmp) / "py", Path(tmp) / "swift"
        generate(py_tmp, swift_tmp)
        drift = []
        for fresh, committed in ((py_tmp, PY_OUT), (swift_tmp, SWIFT_OUT)):
            a, b = tree(fresh), tree(committed) if committed.exists() else {}
            for name in sorted(set(a) | set(b)):
                if a.get(name) != b.get(name):
                    drift.append(str((committed / name).relative_to(ROOT)))
    if drift:
        print("codegen drift: these generated files differ from `make codegen` output (hand-edited or stale):")
        for d in drift:
            print("  " + d)
        return 1
    print(f"codegen: no drift ({len(schemas())} schemas)")
    return 0


def main(argv: list[str]) -> int:
    if "--check" in argv:
        return check()
    generate(PY_OUT, SWIFT_OUT)
    print(f"codegen: {len(schemas())} schemas -> {PY_OUT.relative_to(ROOT)}/, {SWIFT_OUT.relative_to(ROOT)}/Contracts.swift")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
